    // -- CONCURRENCY/RACE CONDITION TESTS

    @Test
    public void testConcurrentAccountCreation() throws Exception {
        int threadCount = 5; // simulates 5 simultaneous account creations
        ExecutorService executor = Executors.newFixedThreadPool(threadCount);
        List<Future<Boolean>> results = new ArrayList<>();

        for (int i = 0; i < threadCount; i++) {
            final int idx = i;
            results.add(executor.submit(() -> db.createAccount("User" + idx, "Test", 25,
                    "user" + idx, "pass", "u" + idx + "@test.com", "1234567890")));
        }
        executor.shutdown();
        executor.awaitTermination(5, TimeUnit.SECONDS);

        for (Future<Boolean> f : results) {
            assertTrue(f.get(), "All concurrent account creations should succeed.");
        }

        // verify the correct number of accounts in the file
        try (BufferedReader br = new BufferedReader(new FileReader(ACCOUNT_FILE))) {
            int lines = 0;
            while (br.readLine() != null) {
                lines++;
            }
            assertEquals(threadCount, lines, "All accounts should be saved correctly in accounts.txt.");
        }
    }

    @Test
    public void testConcurrentReservationCreation() throws Exception {
        // prepare account
        db.createAccount(firstName, lastName, age, username, password, email, phoneNumber);
        generatedID = getLatestAccountID();
        Account account = db.getAccount(generatedID, password);

        String localShowID = "S101";
        String concertSeatFile = "Concert" + localShowID;

        // prepare seats file
        try (FileWriter fw = new FileWriter(concertSeatFile)) {
            fw.write("101\n");
            for (int i = 0; i < 5; i++) {
                fw.write("A" + i + ",A,true,1,50.00\n");
            }
        }

        int threadCount = 5;
        ExecutorService executor = Executors.newFixedThreadPool(threadCount);
        List<Future<Integer>> results = new ArrayList<>();

        for (int i = 0; i < threadCount; i++) {
            final int seatNum = i;
            results.add(executor.submit(() -> db.createReservation(account, "S101",
                    Arrays.asList("A" + seatNum), "2025-12-01", "19:00", 50.0)));
        }
        executor.shutdown();
        executor.awaitTermination(5, TimeUnit.SECONDS);

        for (Future<Integer> f : results) {
            int resID = f.get();
            assertTrue(resID > 0, "Each concurrent reservation should succeed.");
        }

        // verify all reservations exist
        ArrayList<Reservations> reservations = db.getReservationsByAccount(generatedID);
        assertEquals(threadCount, reservations.size(), "All reservations should be recorded correctly.");
    }

