    // helper method to retrieve the actual ID generated by createAccount,
    // since the ID logic is internal to the Account class
    private String getLatestAccountID() throws IOException {
        String lastLine = null;
        try (BufferedReader br = new BufferedReader(new FileReader(ACCOUNT_FILE))) {
            String line;
            while ((line = br.readLine()) != null) {
                if (!line.trim().isEmpty()) {
                    lastLine = line;
                }
            }
        }
        if (lastLine != null) {
            String[] parts = lastLine.split(",");
            // the ID is the last field (index 7) based on the deleteAccount logic
            return parts[7];
        }
        return null;
    }

